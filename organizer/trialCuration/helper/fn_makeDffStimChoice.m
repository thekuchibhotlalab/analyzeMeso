function [X,alignment]=fn_makeDffStimChoice(stim,choice)
%FN_MAKEDFFSTIMCHOICE Concatenate parsed arrays (source event at frame 31).
% 1:29 pre-stim; 30:32 stim 0/1/2; 33:35 choice -3/-2/-1;
% 36 choice onset; 37:100 choice +1:+64. The join is NOT continuous time.
alignment=struct('name','dffStimChoice','nFrames',100,'frameRate',15, ...
    'stimulusFrame',30,'choiceFrame',36,'choicePreFrames',33:35, ...
    'sourceEventFrame',31,'sourceStimFrames',2:33,'sourceChoiceFrames',28:95, ...
    'segment',[ones(1,32),2*ones(1,68)], ...
    'segmentTime',[(-29:2)/15,(-3:64)/15], ...
    'note','Two aligned segments; the boundary between frames 32 and 33 is not elapsed trial time.');
if isempty(stim)||isempty(choice), X=[]; return; end
assert(isfloat(stim)&&isfloat(choice)&&ndims(stim)<=3&&ndims(choice)<=3, ...
    'trialCuration:CompositeShape','Sources must be floating-point neuron x time x trial arrays.');
assert(size(stim,1)==size(choice,1)&&size(stim,3)==size(choice,3), ...
    'trialCuration:CompositeShape','Stimulus and choice arrays must have matching neuron and trial rows.');
X=nan(size(stim,1),100,size(stim,3),'like',stim);
si=alignment.sourceStimFrames; ci=alignment.sourceChoiceFrames;
valid=si<=size(stim,2); X(:,find(valid),:)=stim(:,si(valid),:);
valid=ci<=size(choice,2); X(:,32+find(valid),:)=choice(:,ci(valid),:);
end
